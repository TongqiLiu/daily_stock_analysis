"""Shared evidence and risk contract for built-in and custom analysis skills."""

from __future__ import annotations

from typing import Iterable


def get_shared_skill_evidence_policy(skills: Iterable[object]) -> str:
    """Keep combined/advanced skill prompts within the same evidence boundary."""
    if not list(skills):
        return ""
    return """## 所有技能共同遵守的证据与执行约束

以下约束优先于单个技能里的经验评分、仓位例子和历史知识；组合技能也只能使用同一套事实。

- 事实只来自本轮工具或明确标注的用户输入；列出数据源、数据截至和财报期间。查询时间不等于财报发布时间。知识库只能提出待验证问题，不能补齐财务历史、管理层、分红、行业比较或研报事实。
- 缺失、过期、不可比数据标记 missing/partial，不等于中性、零或通过；从评分分母排除并降低覆盖率。关键字段不足时结论为证据不足/等待，不给强方向或可执行建议。
- 区分公司质量、合理估值、市场方向与交易动作。历史低估值分位不等于内在低估；方向偏多不等于现在可以买；模型分数、共振数量和主观情景权重都不是胜率。
- 具体仓位或张数必须有账户规模、已持仓、风险预算、币种、合约乘数及有证据的失效条件。没有这些输入只给方法，不根据评分、理论级别或公司质量直接给固定重仓/满仓比例。日内 T 的比例仅描述现有持仓中可机动部分的上限参考，不能当账户配置，也不能超过可卖股数。
- 新仓、加仓和回补分别按拟成交价、新失效位、下一阻力及总敞口检查；短线量化价位不足或收益风险不合适则等待。长期估值区间不是短线止损，不能强行编造止损来凑盈亏比。已有持仓管理不能被“禁止新开仓”替代。
- 日线与日内信号区分周期和已收盘状态；未收盘不能写成确认。报价延迟、停牌、财报跳空、价差和交易费用可能使图上信号无法成交。
- 含 get_stock_backtest_summary 的技能须读取当前标的已有股票回测，不指定窗口时采用工具返回的有效窗口。披露窗口、引擎、样本及完成/不足数量、入场和成本口径；区分方向命中率、做多交易盈利率、平均收益。披露工具是否实际重放，旧存量统计不等于当前代码已复现的成绩。空仓零收益、重叠窗口及同股重复样本不能冒充独立交易或提升可信度。
- 股票历史报告的表现不能归因给当前技能；没有技能独立样本就写“技能效果未验证”。短期回测不能证明多年价投、3m/5m 日内或期权策略有效，也不能以短期命中率高低支持或否定长期护城河、内在价值与投资论点。无样本时保留证据缺口，不改用全市场胜率，不重新编造历史信号，不依据少量样本自动调权或扩大仓位。
"""
